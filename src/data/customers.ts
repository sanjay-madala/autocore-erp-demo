export type CreditTier = 'Excellent 750+' | 'Good 700-749' | 'Fair 650-699' | 'Subprime <650' | 'No Score';
export type ConsentStatus = 'opted_in' | 'opted_out' | 'pending' | 'verbal_opt_in';

export interface CoBuyer {
  firstName: string;
  lastName: string;
  relationship: string;
  phone?: string;
  creditTier?: CreditTier;
}

export interface VehicleOwned {
  year: number;
  make: string;
  model: string;
  vin: string;
  payoff?: number;
  lender?: string;
}

export interface Customer {
  id: string; // file number — also used as customerId elsewhere
  fileNumber: string;
  masterId: string; // golden record id — multiple ids can share same masterId if deduped
  firstName: string;
  lastName: string;
  email: string;
  phone: string; // normalized E.164
  secondaryPhone?: string;
  address: string;
  city: string;
  state: string;
  zip: string;
  dlNumber: string; // masked except last 4 in UI
  dob: string; // ISO date
  creditTier: CreditTier;
  creditScore?: number;
  employer?: string;
  occupation?: string;
  incomeAnnual?: number;
  coBuyer?: CoBuyer;
  vehiclesOwned: VehicleOwned[];
  rooftops: ('dtown' | 'north' | 'westside')[];
  tags: string[];
  doNotContact: boolean;
  consentStatus: ConsentStatus;
  consentDate?: string;
  createdAt: string;
  updatedAt: string;
  mergedFrom?: string[]; // duplicate ids merged into this master
  duplicateOf?: string; // if this record is a duplicate, points to master id
  isDuplicate?: boolean;
  lifetimeValue: number; // gross profit contributed
  communicationPrefs: { email: boolean; sms: boolean; phone: boolean };
  notes?: string;
  // Compliance (F5)
  ofacStatus: 'clear' | 'pending' | 'hit_review';
  redFlagsScore: number; // 0-100, lower is better
  idVerified: boolean;
}

