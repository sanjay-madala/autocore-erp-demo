export type LeadSource = 'Website' | 'ThirdParty' | 'Phone' | 'Showroom' | 'Chat' | 'ServiceDrive';
export type LeadSourceDetail = 'Website — SEO' | 'Website — Paid Search' | 'Cars.com' | 'AutoTrader' | 'CarGurus' | 'Phone — Inbound' | 'Showroom Walk-In' | 'Chat — Drift' | 'Service Drive' | 'Facebook Marketplace';
export type LeadStatus = 'new' | 'contacted' | 'appointment_set' | 'shown' | 'sold' | 'lost' | 'duplicate' | 'unqualified';
export type LeadPriority = 'hot' | 'warm' | 'cold';

export interface Lead {
  id: string;
  customerId: string; // resolves to master customerId
  customerName: string;
  masterId: string;
  isDuplicateLead: boolean;
  duplicateOfLeadId?: string; // if duplicate, points to primary lead
  source: LeadSource;
  sourceDetail: LeadSourceDetail;
  campaign?: string;
  rooftopId: 'dtown' | 'north' | 'westside';
  rooftopName: string;
  vehicleOfInterestId?: string;
  vehicleOfInterest?: string; // human readable
  stockNo?: string;
  status: LeadStatus;
  priority: LeadPriority;
  owner: string; // BDC / salesperson
  ownerTeam: 'BDC' | 'Internet' | 'Showroom' | 'Fleet';
  // Speed-to-lead timestamps (critical KPI)
  createdAt: string;
  firstResponseAt?: string;
  speedToLeadSec?: number; // null if not yet responded
  speedToLeadGrade?: 'A' | 'B' | 'C' | 'D' | 'F'; // A <2min, B <5, C <15, D <60, F >60 or none
  lastContactAt?: string;
  appointmentAt?: string;
  shownAt?: string;
  // Contact attempts
  attempts: number;
  // Scores
  aiScore?: number; // 0-100 likelihood to close
  // Outcome
  dealId?: string;
  lostReason?: string;
  notes?: string;
  // Comms consent snapshot
  consentStatus: 'opted_in' | 'opted_out' | 'pending';
  // Extra — for dedup UI
  dedupKeys: { phone: string; email: string };
}

function speedGrade(sec?: number): Lead['speedToLeadGrade'] {
  if (sec == null) return 'F';
  if (sec < 120) return 'A';
  if (sec < 300) return 'B';
  if (sec < 900) return 'C';
  if (sec < 3600) return 'D';
  return 'F';
}

